/** Export the actual executable UI materials. Never maintain a second answer key. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { load } = require('./learningModuleLoader.cjs');
const root = path.resolve(__dirname, '../src/features/learning');
const destination = path.resolve(__dirname, '../../back/src/learning/feedback/materials.json');
const versionsPath = path.join(root, 'assessment/materialVersions.ts');
const registry = load(path.join(root, 'app/unitRegistry.ts')).learningUnits;
const phasePurposes = [
 'この単元の問題設定と、アルゴリズムを使う目的を知る。',
 '図の状態を一手ずつ追い、アルゴリズムの手順と判断規則を確かめる。',
 '図の問題で、次の操作と判断の理由を確認する。',
 '図の動きとコードの各処理を対応づけて読む。',
 'コードの空欄を選び、各処理の役割と動作との対応を確認する。',
 '条件の異なる問題やコードの並べ替えに取り組み、手順を適用する。',
 '自分でコードを書き、実行結果をテストして確認・修正する。',
];
const plain = value => JSON.parse(JSON.stringify(value));
function objectWith(module, key) { return Object.values(module).find(v => v && typeof v === 'object' && key in v); }
function build() {
 const current = {}, units = {};
 for (const unit of registry) {
  const base = path.join(root, unit.kind);
  const execution = objectWith(load(path.join(base,'execution/execution.content.ts')), 'steps');
  const mapping = objectWith(load(path.join(base,'code-mapping/codeMapping.content.ts')), 'steps');
  const phases = unit.phases.map(p=>({id:p.id,phase:p.phase,name:p.formalName,goal:phasePurposes[p.phase-1],bridge:p.bridge??null}));
  const assessments = [];
  for (const [dir,file] of [['check','check'],['code-check','codeCheck'],['consolidation','consolidation']]) {
   const contentModule = load(path.join(base,dir,`${file}.content.ts`));
   const content = objectWith(contentModule, 'questions');
   const source = dir==='check' ? execution : mapping;
   const sceneGetter = Object.entries(contentModule).find(([k,v])=>/^get.*CheckScene$/.test(k)&&typeof v==='function')?.[1];
   const questions = content.questions.map(q=>{
    const scene = q.scene ?? (sceneGetter && dir==='check' ? sceneGetter(q) : source.steps.find(s=>s.id===q.stepId)?.canvas);
    const code = content.code ?? source.code ?? null;
    const reviewSteps = q.reviewStepIds.map(id=>{
     const step = source.steps.find(s=>s.id===id);
     assert(step, `${unit.kind}/${content.id}/${q.id}: missing review ${id}`);
     return {id:step.id,caption:step.caption??null,codeFocus:step.codeFocus??null};
    });
    assert(scene || code, `${content.id}/${q.id}: no scene/code`);
    return plain({...q, scene:scene??null, code, reviewSteps,
     explanation:{correct:q.correctFeedback??null,incorrect:q.incorrectFeedback??content.retryFeedback??null,
      basis:'correctAnswer・scene・code・reviewStepsは画面教材の定義から取得。説明文が未定義ならnull。'}});
   });
   assessments.push({id:content.id,phaseKey:content.id,phase:content.phase,questions});
  }
  const material = plain({courseId:unit.courseId,title:unit.title,intro:unit.intro,
   phases:phases.map(p=>({...p,focusQuestions:assessments.find(a=>a.phase===({2:3,4:5}[p.phase]??p.phase))?.questions.map(q=>q.prompt)??[]})),assessments});
  const version = 'sha256:'+crypto.createHash('sha256').update(JSON.stringify(material)).digest('hex');
  units[version] = material;
  for(const a of assessments)current[a.id] = version;
 }
 return {current,units};
}
const built = build();
const archived = JSON.parse(fs.readFileSync(destination,'utf8'));
if(process.argv.includes('--check')) {
 assert.deepEqual(archived.current,built.current,'UI changed: run npm run sync:feedback-materials and commit the archive');
 assert.deepEqual(plain(load(versionsPath).default),built.current);
 for(const [version,material] of Object.entries(built.units))assert.deepEqual(archived.revisions[version],material);
 console.log(`PASS: ${registry.length} units, ${Object.keys(built.current).length} assessments match the UI material archive`);
} else {
 const next={schemaVersion:1,current:built.current,revisions:{...archived.revisions,...built.units}};
 fs.writeFileSync(destination,JSON.stringify(next,null,2)+'\n');
 fs.writeFileSync(versionsPath,'// Generated by scripts/syncFeedbackMaterials.cjs. Do not edit by hand.\nexport default '+JSON.stringify(built.current,null,2)+' as const;\n');
 console.log('Updated material archive and browser version manifest; historical revisions retained.');
}
