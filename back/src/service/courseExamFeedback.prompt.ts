export const buildCourseExamFeedbackPrompt = ({
  condition,
  learningLog,
  appState,
  availableActions,
  hexadProfile,
}: {
  condition: FeedbackCondition;
  learningLog: unknown;
  appState: unknown;
  availableActions: unknown;
  hexadProfile: unknown | null;
}) => {
  const common = buildCommonCourseExamFeedbackPrompt({
    learningLog,
    appState,
    availableActions,
  });
  if (condition === FeedbackCondition.STANDARD) return common;
  if (!hexadProfile) {
    throw new Error("PERSONALIZED feedback requires a HEXAD profile");
  }
  return `${common}\n\n${buildPersonalizedCourseExamFeedbackSection(hexadProfile)}`;
};
